// The text for key in the current language (English if it has no entry), with each {name}
// replaced by params[name].
export function t(key, params = {}) {
  const text = TABLES[lang][key] ?? EN[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (all, name) => (name in params ? String(params[name]) : all));
}
